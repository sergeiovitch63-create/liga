function toSlug(text) {
  return text
    .toLowerCase()
    .replace(/[()]/g, "")
    .replace(/[+]/g, "plus")
    .replace(/[^\p{L}\p{N}\s-]/gu, " ")
    .trim()
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-");
}

const slugCount = {};
export const repairServices = repairPriceItems.map((item, index) => {
  const base = toSlug(item.name) || `service-${index + 1}`;
  slugCount[base] = (slugCount[base] || 0) + 1;
  const slug = slugCount[base] === 1 ? base : `${base}-${slugCount[base]}`;
  return {
    id: index + 1,
    slug,
    ...item
  };
});

export function getRepairPath(service) {
  return `/remont/${encodeURIComponent(service.slug)}`;
}

export function findRepairBySlug(slug) {
  const decoded = decodeURIComponent(slug);
  return repairServices.find((s) => s.slug === decoded) ?? null;
}

export function generateRepairStaticParams() {
  return repairServices.map((s) => ({ slug: s.slug }));
}
