export const partsWithId = parts.map((row, index) => ({
  id: index + 1,
  name: row[0],
  ref: row[1] || "",
  price: row[2],
  stock: row[3]
}));

const refCount = {};
for (const p of partsWithId) {
  if (p.ref) refCount[p.ref] = (refCount[p.ref] || 0) + 1;
}

/** Valeur brute du segment d’URL (ref unique ou id). */
export function getPartUrlSegment(p) {
  if (p.ref && refCount[p.ref] === 1) return p.ref;
  return String(p.id);
}

export function getPartPath(p) {
  return `/parts/${encodeURIComponent(getPartUrlSegment(p))}`;
}

/**
 * Résout une pièce depuis le segment d’URL : id numérique 1…N ou référence exacte.
 */
export function findPartByUrlSegment(segment) {
  const decoded = decodeURIComponent(segment);
  if (/^\d+$/.test(decoded)) {
    const n = parseInt(decoded, 10);
    if (n >= 1 && n <= partsWithId.length) return partsWithId[n - 1];
    return null;
  }
  return partsWithId.find((x) => x.ref === decoded) ?? null;
}

export function generatePartStaticParams() {
  return partsWithId.map((p) => ({ ref: getPartUrlSegment(p) }));
}
